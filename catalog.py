def protection(enemy, mapname):
    row = CATALOG.get(enemy.model)
    if row and row['category'] == '보호 대상':
        return '보스 또는 NPC'
    if enemy.talk > 0:
        return '대화 또는 NPC 이벤트가 있는 개체'
    if (mapname,enemy.model,enemy.entity) in BOSS_PLACEMENTS:
        return '보스 전투 개체'
    if set(enemy.groups) & BOSS_GROUPS.get(mapname,set()):
        return '보스 전투 참여 개체'
    return None


def corpus_policy(folder):
    """Optional exact-map fingerprint allowlist used by release builds."""
    path = Path(folder) / 'supported_maps.json'
    return json.loads(path.read_text(encoding='utf-8')) if path.exists() else {}
